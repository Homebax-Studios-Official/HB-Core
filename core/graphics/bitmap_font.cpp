GlyphInfo glyphFor(char32_t cp) {
    GlyphInfo g{kAscii[0], {0, 0}};
    auto ascii = [&](char c) { g.rows = kAscii[static_cast<unsigned char>(c) - 32]; };
    if (cp >= 32 && cp <= 126) { ascii(static_cast<char>(cp)); return g; }
    switch (cp) {
        case 0xA0: case 0x2002: case 0x2003: case 0x2009: ascii(' '); return g;
        case 0x2018: case 0x2019: ascii('\''); return g;
        case 0x201C: case 0x201D: case 0xAB: case 0xBB: ascii('"'); return g;
        case 0x2013: case 0x2014: case 0x2212: ascii('-'); return g;
        case 0x2026: ascii('.'); return g;
        case 0xB7: case 0x2022: ascii('*'); return g;
        case 0xA9: ascii('c'); return g;
        case 0xAE: ascii('R'); return g;
        default: break;
    }
    for (const auto& f : kFold) {
        if (f.cp == cp) {
            ascii(f.base);
            g.mark[0] = kMarkBits[f.mark][0];
            g.mark[1] = kMarkBits[f.mark][1];
            return g;
        }
    }
    ascii('?');
    return g;
}

float measureText(std::string_view utf8, float fontSize) {
    size_t i = 0, n = 0;
    while (i < utf8.size()) { decodeUtf8(utf8, i); ++n; }
    return static_cast<float>(n) * glyphAdvance(fontSize);
}

