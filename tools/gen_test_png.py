#!/usr/bin/env python3
"""Generates tests/test_png_data.h: PNG files covering color types, bit depths, filters and Adam7,
each with its expected RGBA output computed independently of the C++ decoder.
Usage: python3 tools/gen_test_png.py > tests/test_png_data.h"""
import struct, zlib, base64

def chunk(t, d):
    c = struct.pack(">I", len(d)) + t + d
    return c + struct.pack(">I", zlib.crc32(t + d) & 0xffffffff)

def pack_row(samples, depth):
    if depth == 8:
        return bytes(samples)
    if depth == 16:
        return b"".join(struct.pack(">H", s) for s in samples)
    out = bytearray(); acc = 0; bits = 0
    for s in samples:
        acc = (acc << depth) | s; bits += depth
        if bits == 8:
            out.append(acc); acc = 0; bits = 0
    if bits:
        out.append(acc << (8 - bits))
    return bytes(out)

def paeth(a, b, c):
    p = a + b - c; pa = abs(p - a); pb = abs(p - b); pc = abs(p - c)
    if pa <= pb and pa <= pc: return a
    return b if pb <= pc else c

def filt(row, prev, bpp, ft):
    out = bytearray()
    for i, x in enumerate(row):
        a = row[i - bpp] if i >= bpp else 0
        b = prev[i]; c = prev[i - bpp] if i >= bpp else 0
        if ft == 0: v = x
        elif ft == 1: v = x - a
        elif ft == 2: v = x - b
        elif ft == 3: v = x - ((a + b) >> 1)
        else: v = x - paeth(a, b, c)
        out.append(v & 255)
    return bytes([ft]) + bytes(out)

ADAM7 = [(0,0,8,8),(4,0,8,8),(0,4,4,8),(2,0,4,4),(0,2,2,4),(1,0,2,2),(0,1,1,2)]

def make_png(w, h, ctype, depth, pix, interlace=False, palette=None, trns=None):
    ch = {0:1, 2:3, 3:1, 4:2, 6:4}[ctype]
    bpp = max(1, ch * depth // 8)
    passes = ADAM7 if interlace else [(0,0,1,1)]
    raw = bytearray(); n = 0
    for (x0, y0, dx, dy) in passes:
        xs = list(range(x0, w, dx)); ys = list(range(y0, h, dy))
        if not xs or not ys: continue
        prev = bytes((len(xs) * ch * depth + 7) // 8)
        for y in ys:
            samples = [s for x in xs for s in pix[y][x]]
            row = pack_row(samples, depth)
            raw += filt(row, prev, bpp, n % 5); n += 1
            prev = row
    ihdr = struct.pack(">IIBBBBB", w, h, depth, ctype, 0, 0, 1 if interlace else 0)
    out = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", ihdr)
    if palette: out += chunk(b"PLTE", bytes(c for rgb in palette for c in rgb))
    if trns is not None: out += chunk(b"tRNS", trns)
    out += chunk(b"IDAT", zlib.compress(bytes(raw), 9)) + chunk(b"IEND", b"")
    return out

def to8(v, depth):
    if depth == 16: return v >> 8
    if depth == 8: return v
    return v * 255 // ((1 << depth) - 1)

def expected(w, h, ctype, depth, pix, palette=None, trns=None, key=None):
    out = []
    for y in range(h):
        for x in range(w):
            s = pix[y][x]
            if ctype == 0:
                g = to8(s[0], depth); a = 0 if key is not None and s[0] == key[0] else 255; out += [g, g, g, a]
            elif ctype == 2:
                a = 0 if key is not None and tuple(s) == tuple(key) else 255
                out += [to8(s[0], depth), to8(s[1], depth), to8(s[2], depth), a]
            elif ctype == 3:
                p = palette[s[0]]; a = trns[s[0]] if trns is not None and s[0] < len(trns) else 255
                out += [p[0], p[1], p[2], a]
            elif ctype == 4:
                g = to8(s[0], depth); out += [g, g, g, to8(s[1], depth)]
            else:
                out += [to8(v, depth) for v in s]
    return out

def pattern(w, h, ch, depth):
    mx = (1 << depth) - 1
    return [[[ (x * 31 + y * 17 + c * 53 + 7) % (mx + 1) for c in range(ch)] for x in range(w)] for y in range(h)]

cases = []
def add(name, w, h, ctype, depth, interlace=False, palette=None, trns=None, key=None):
    ch = {0:1, 2:3, 3:1, 4:2, 6:4}[ctype]
    pix = pattern(w, h, ch, depth)
    if ctype == 3:
        for row in pix:
            for p in row: p[0] %= len(palette)
    png = make_png(w, h, ctype, depth, pix, interlace, palette, trns if ctype == 3 else (key and b"".join(struct.pack(">H", k) for k in key)))
    cases.append((name, w, h, png, expected(w, h, ctype, depth, pix, palette, trns, key)))

pal4 = [(i * 16 % 256, 255 - i * 9, (i * 77) % 256) for i in range(4)]
add("rgba8", 13, 9, 6, 8)
add("rgb8_adam7", 11, 10, 2, 8, interlace=True)
add("gray16", 7, 5, 0, 16)
add("gray1", 19, 4, 0, 1)
add("gray4_key", 9, 3, 0, 4, key=(5,))
add("palette2_trns", 10, 6, 3, 2, palette=pal4, trns=bytes([255, 128, 0]))
add("graya8", 6, 6, 4, 8)
add("rgb16_adam7", 9, 9, 2, 16, interlace=True)

def arr(b): return ",".join(str(x) for x in b)
print("// Generated by tools/gen_test_png.py - do not edit.")
print("#pragma once\n#include <cstdint>\n#include <vector>\n")
print("struct PngCase { const char* name; int w, h; std::vector<uint8_t> png; std::vector<uint8_t> rgba; };")
print("inline std::vector<PngCase> pngCases() {\n  return {")
for name, w, h, png, rgba in cases:
    print('    {"%s", %d, %d, {%s}, {%s}},' % (name, w, h, arr(png), arr(rgba)))
print("  };\n}")
# 4x4 solid red PNG as base64 for <img src="data:...">
red = make_png(4, 4, 2, 8, [[[255, 0, 0]] * 4] * 4)
print('inline const char* kRedPngDataUrl = "data:image/png;base64,%s";' % base64.b64encode(red).decode())
